const files = import.meta.glob<string>('../assets/images/**/*.{png,webp,jpg,jpeg,svg}', {
  eager: true,
  import: 'default',
})

export type ImageAsset = {
  src: string
  width: number
  height: number
  alt: string
}

function asset(path: string, width: number, height: number, alt: string): ImageAsset {
  const src = files[`../assets/images/${path}`]
  if (!src) throw new Error(`Missing image: ${path}`)
  return { src, width, height, alt }
}

